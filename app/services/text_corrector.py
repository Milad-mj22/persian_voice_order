"""
اصلاح متن خروجی Whisper برای فارسی محاوره‌ای
"""
import re
from app.core.logger import logger


class PersianTextCorrector:
    """اصلاح اشتباهات رایج Whisper در فارسی"""

    # دیکشنری اصلاح — کلید: اشتباه، مقدار: درست
    REPLACEMENTS = {
        # کلمات پرکاربرد
        "می خواهم": "میخوام",
        "می خواهیم": "میخوایم",
        "می خواهید": "میخواید",
        "می خواهد": "میخواد",
        "نمی خواهم": "نمیخوام",
        "نمی خواهیم": "نمیخوایم",
        "بفرمایید": "بفرمایید",
        "بفرمائید": "بفرمایید",
        "می شود": "میشه",
        "نمی شود": "نمیشه",
        "می شود": "میشه",
        "می کنم": "میکنم",
        "می کنی": "میکنی",
        "می کند": "میکنه",
        "می کنیم": "میکنیم",
        "می کنید": "میکنید",
        "می کنند": "میکنن",
        "چی می خواهید": "چی میخواید",
        "چه می خواهید": "چی میخواید",
        "آیا": "آیا",
        "بله": "بله",
        "آره": "آره",
        "بلی": "بله",
        "نخیر": "نه",
        "خیر": "نه",
        "بله میخواهم": "بله میخوام",

        # اعداد (اعداد فارسی)
        "۱": "1", "۲": "2", "۳": "3", "۴": "4", "۵": "5",
        "۶": "6", "۷": "7", "۸": "8", "۹": "9", "۰": "0",

        # کلمات غذایی
        "پی زا": "پیتزا",
        "پیزا": "پیتزا",
        "پیتزا": "پیتزا",
        "برگر": "برگر",
        "برگر": "برگر",
        "ساندویچ": "ساندویچ",
        "ساندویچ": "ساندویچ",
        "نوشابه": "نوشابه",
        "نوشابه": "نوشابه",
        "کوکا کولا": "کوکاکولا",
        "کوکاکولا": "کوکاکولا",

        # کلمات آدرس
        "خیابان": "خیابان",
        "خیابون": "خیابون",
        "کوچه": "کوچه",
        "پلاک": "پلاک",
        "طبقه": "طبقه",
        "واحد": "واحد",

        # سایر
        "تومان": "تومان",
        "هزار": "هزار",
        "میلیون": "میلیون",
        "تحویل": "تحویل",
        "ادرس": "آدرس",
        "ادرس": "آدرس",
    }

    # الگوهای regex برای اصلاح
    PATTERNS = [
        # تبدیل نیم‌فاصله اشتباه
        (re.compile(r"\s+"), " "),
        # حذف کاراکترهای اضافی
        (re.compile(r"[^\u0600-\u06FF\s\d\w\.,،؟!:؛\-()]"), ""),
    ]

    @classmethod
    def correct(cls, text: str) -> str:
        """اصلاح متن"""
        if not text or not text.strip():
            return text

        original = text
        text = text.strip()

        # اعمال جایگزینی‌ها
        for wrong, right in cls.REPLACEMENTS.items():
            if wrong != right:  # فقط اگه واقعاً تغییر باشه
                text = text.replace(wrong, right)

        # اعمال pattern ها
        for pattern, replacement in cls.PATTERNS:
            text = pattern.sub(replacement, text)

        text = text.strip()

        if text != original:
            logger.debug(f"متن اصلاح شد: {original!r} → {text!r}")

        return text